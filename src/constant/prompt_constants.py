# 长期记忆提取提示词：LLM 根据本轮对话更新用户档案
# 规则：只记录长期有效事实，无新信息时输出"无"，有新信息输出合并后完整档案
MEMORY_EXTRACT_PROMPT = """你是长期记忆管理器，负责维护用户档案。

    根据【本轮对话】，更新【已有档案】：
    1. 只记录长期有效的事实（如姓名、职业、身份、偏好、习惯、目标等），忽略一次性请求与寒暄。
    2. 若本轮没有值得记录的新信息，只输出一个词：无。
    3. 有新信息则输出合并后的完整档案，直接输出文本，不要任何解释或 JSON。

    【已有档案】
    {old_profile}

    【本轮对话】
    用户：{input_str}
    助手：{llm_output}"""

# 意图分类器提示词：判断用户问题是否需要检索知识库
# 规则：需要具体知识/事实→yes，寒暄/闲聊/常识/仅靠对话即可回答→no，只输出 yes 或 no
# 注意：知识库内容可由用户自定义入库，分类器不得绑定任何业务主题，只按"是否需要外部知识"通用判定
CLASSIFIER_PROMPT = """你是问答路由，判断用户问题是否需要检索当前知识库。

    需要检索（输出 yes）：
    - 问题需要具体的知识、事实、数据或文档内容才能回答（技术细节、操作步骤、配置参数、规范说明、专有名词解释等）；
    - 问题指向某个特定领域，且答案不在对话上下文中，需要查证知识库才能给出准确回答；
    - 用户明确要求基于知识库/资料回答。

    不需要检索（输出 no）：
    - 寒暄问候、自我介绍、闲聊、情绪表达；
    - 通用常识（数学、语言、生活类等无需查证即可回答的问题）；
    - 仅凭当前对话上下文即可回答的问题（如对刚才回答的追问、复述、确认）；
    - 与知识库内容无关的开放式创作或话题。

    只输出一个词：yes 或 no。"""

# 无信息标记集合：LLM 返回这些值时表示本轮无新增长期记忆
NO_INFO_MARKS = {"（无）", "无", "无新信息", "暂无", "无新增信息"}
